OBSOLETE_CUSTOM_FIELDS = ("Purchase Receipt Item-nir_receipt_section",)


def setup():
	"""Idempotent: safe to run on every migrate."""
	for name in OBSOLETE_CUSTOM_FIELDS:
		if frappe.db.exists("Custom Field", name):
			frappe.delete_doc("Custom Field", name, ignore_permissions=True)
	create_custom_fields(CUSTOM_FIELDS, update=True)
	from pharmacy.overrides.rider import setup_rider_permissions

	setup_rider_permissions()
	from pharmacy.online.picking import setup_picker_permissions

	setup_picker_permissions()
	create_uoms()
	enable_track_changes()
	sync_non_sellable()
	create_adjustment_reasons()
	create_pos_discount_limits()
	create_item_groups()
	disable_retired_gst_templates()


POS_DISCOUNT_LIMITS = {
	# role: (max manual discount %, may approve others' overrides)
	"Store Pharmacist": (5, 0),
	"Area Manager": (20, 1),
	"Pharmacy Management": (30, 1),
}


def create_pos_discount_limits():
	for role, (limit, approves) in POS_DISCOUNT_LIMITS.items():
		if frappe.db.exists("Role", role) and not frappe.db.exists("POS Discount Limit", role):
			frappe.get_doc({"doctype": "POS Discount Limit", "role": role, "max_discount_pct": limit,
				"can_approve_overrides": approves}).insert(ignore_permissions=True)


def create_adjustment_reasons():
	for reason, applies_to in ADJUSTMENT_REASONS.items():
		if not frappe.db.exists("Stock Adjustment Reason", reason):
			frappe.get_doc({"doctype": "Stock Adjustment Reason", "reason": reason, "applies_to": applies_to}).insert(
				ignore_permissions=True
			)


def create_uoms():
	for uom in UOMS:
		if not frappe.db.exists("UOM", uom):
			frappe.get_doc({"doctype": "UOM", "uom_name": uom, "must_be_whole_number": 1}).insert(
				ignore_permissions=True
			)


def enable_track_changes():
	for doctype in TRACK_CHANGES_DOCTYPES:
		make_property_setter(
			doctype, None, "track_changes", 1, "Check", for_doctype=True, validate_fields_for_doctype=False
		)


def create_item_groups():
	# the root group is created by the setup wizard; until then there is nothing to attach to
	root = frappe.db.get_value("Item Group", {"is_group": 1, "parent_item_group": ("is", "not set")})
	if not root:
		return

	for group, children in ITEM_GROUPS.items():
		create_item_group(group, root, is_group=bool(children))
		for child in children:
			create_item_group(child, group)


def create_item_group(name, parent, is_group=False):
	if frappe.db.exists("Item Group", name):
		return

	frappe.get_doc(
		{
			"doctype": "Item Group",
			"item_group_name": name,
			"parent_item_group": parent,
			"is_group": int(is_group),
		}
	).insert(ignore_permissions=True)
